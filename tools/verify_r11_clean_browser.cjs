const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const {loginForVerification}=require('./browser_auth.cjs')
const fs=require('node:fs')
async function main(){
  const base=process.argv[2];assert.match(base,/^http:\/\/127\.0\.0\.1:\d+$/)
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'})
  try{
    const page=await browser.newPage({viewport:{width:1365,height:900}})
    const errors=[];page.on('pageerror',e=>errors.push(e.message))
    await loginForVerification(page,base)
    await page.goto(base)
    await page.getByRole('button',{name:'管理后台',exact:true}).click()
    await page.getByRole('region',{name:'后台概览'}).getByText(/owner 的管理概览/).waitFor()
    await page.getByRole('button',{name:'模型渠道',exact:true}).click()
    await page.locator('#admin-model-key').waitFor()
    assert.equal(await page.locator('#admin-model-key').inputValue(),'')
    await page.setViewportSize({width:390,height:844})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    fs.mkdirSync('logs/r11',{recursive:true})
    await page.screenshot({path:'logs/r11/clean-start-browser.png',fullPage:true})
    await page.getByRole('button',{name:/退出登录/}).click()
    await page.getByRole('heading',{name:'登录 RayAgent',exact:true}).waitFor()
    assert.equal((await page.request.get(base+'/api/admin/models')).status(),401)
    assert.deepEqual(errors,[])
    console.log('PASS bundled-container browser: owner login, private admin, empty credentials, mobile, logout; no external model calls')
  }finally{await browser.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
